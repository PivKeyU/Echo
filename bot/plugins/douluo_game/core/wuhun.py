def wuhun_by_key(key: str) -> dict[str, Any] | None:
    for wuhun in WUHUN_CATALOG:
        if wuhun["key"] == str(key or ""):
            return wuhun
    return None


def random_wuhun() -> dict[str, Any]:
    """品质加权随机武魂(珍品/神品低概率)。

    先按品质权重抽取品质,再在该品质内均匀抽取,保证神品始终约 2%,
    不受各品质武魂条目数量影响。
    """
    weights = {
        "凡品": 42,
        "良品": 30,
        "精品": 18,
        "珍品": 8,
        "神品": 2,
    }
    by_quality: dict[str, list[dict[str, Any]]] = {}
    for item in WUHUN_CATALOG:
        by_quality.setdefault(str(item.get("quality") or "凡品"), []).append(item)
    qualities = [q for q in weights if by_quality.get(q)]
    if not qualities:
        return dict(random.choice(WUHUN_CATALOG))
    total = sum(int(weights[q]) for q in qualities)
    roll = random.randint(1, total)
    acc = 0
    chosen = qualities[-1]
    for q in qualities:
        acc += int(weights[q])
        if roll <= acc:
            chosen = q
            break
    return dict(random.choice(by_quality[chosen]))
